import assert from "node:assert/strict";
import { Pool } from "pg";
import { drizzle } from "drizzle-orm/node-postgres";
import { and, eq } from "drizzle-orm";
import { ulid } from "ulid";
import * as dbs from "@agentos/database";
import { businessAutomationAllowed, createTrustedBusinessContext } from "@agentos/shared";
import { oneCalendarMonthFrom, PostgresTrialService } from "@agentos/trial";

const databaseUrl = process.env.DATABASE_URL; if (!databaseUrl) throw new Error("DATABASE_URL_REQUIRED");
const pool = new Pool({ connectionString: databaseUrl }); const db = drizzle(pool);
let now = new Date("2027-01-31T10:15:00.000Z"); const trial = new PostgresTrialService(db, () => now);
const businessId = ulid(); const otherBusinessId = ulid(); const userId = ulid();
const agency = createTrustedBusinessContext({ businessId, principal: { kind: "user", userId, sessionId: ulid() }, source: "test_harness", traceId: ulid(), capabilityGrants: ["business.read", "business.manage"] });
try {
  assert.equal(oneCalendarMonthFrom(now).toISOString(), "2027-02-28T10:15:00.000Z");
  await db.insert(dbs.businesses).values([{ id: businessId, name: "Trial fixture" }, { id: otherBusinessId, name: "Other business" }]);
  await db.insert(dbs.users).values({ id: userId, name: "Agency operator", email: `${userId}@example.test` });
  await db.insert(dbs.businessMemberships).values({ id: ulid(), businessId, userId, role: "OWNER" });
  let row = (await db.select().from(dbs.businesses).where(eq(dbs.businesses.id, businessId)))[0]!;
  assert.equal(businessAutomationAllowed(row, now), false);
  const activated = await trial.activate(agency);
  assert.equal(activated.startedAt?.toISOString(), now.toISOString());
  assert.equal(activated.endsAt?.toISOString(), "2027-02-28T10:15:00.000Z");
  assert.equal(businessAutomationAllowed({ state: activated.state, disabled: activated.disabled, trialStartedAt: activated.startedAt, trialEndsAt: activated.endsAt, trialExpiryBehavior: activated.expiryBehavior }, now), true);
  await assert.rejects(trial.activate(agency), /TRIAL_ALREADY_STARTED/);
  assert.equal(await trial.expireDue(new Date("2027-02-26T10:15:00.000Z")), 0);
  assert.equal(await trial.expireDue(new Date("2027-02-26T10:15:00.000Z")), 0);
  assert.equal((await db.select().from(dbs.notifications).where(and(eq(dbs.notifications.businessId, businessId), eq(dbs.notifications.type, "TRIAL_ENDING")))).length, 1);
  const queuedWarnings = [ulid(), ulid()];
  await db.insert(dbs.businesses).values(queuedWarnings.map((id) => ({ id, name: "Warning pagination fixture", trialStartedAt: now, trialEndsAt: new Date("2027-03-01T10:15:00.000Z") })));
  await db.insert(dbs.businessMemberships).values(queuedWarnings.map((id) => ({ id: ulid(), businessId: id, userId, role: "OWNER" as const })));
  assert.equal(await trial.expireDue(new Date("2027-02-26T10:15:00.000Z"), 1), 0);
  for (const id of queuedWarnings) assert.equal((await db.select().from(dbs.notifications).where(and(eq(dbs.notifications.businessId, id), eq(dbs.notifications.type, "TRIAL_ENDING")))).length, 1);
  assert.equal(await trial.expireDue(new Date("2027-02-28T10:14:59.000Z")), 0);
  now = new Date("2027-02-28T10:15:00.000Z");
  assert.equal(await trial.expireDue(), 1); assert.equal(await trial.expireDue(), 0);
  row = (await db.select().from(dbs.businesses).where(eq(dbs.businesses.id, businessId)))[0]!;
  assert.equal(row.state, "EXPIRED"); assert.equal(businessAutomationAllowed(row, now), false);
  await trial.setExpiryBehavior(agency, "CONTINUE_AUTOMATION");
  row = (await db.select().from(dbs.businesses).where(eq(dbs.businesses.id, businessId)))[0]!;
  assert.equal(businessAutomationAllowed(row, now), true);
  await trial.overrideState(agency, "PAUSED");
  row = (await db.select().from(dbs.businesses).where(eq(dbs.businesses.id, businessId)))[0]!;
  assert.equal(businessAutomationAllowed(row, now), false);
  const extended = await trial.extend(agency, new Date("2027-03-31T10:15:00.000Z"));
  assert.equal(extended.state, "TRIAL"); assert.equal(extended.endsAt?.toISOString(), "2027-03-31T10:15:00.000Z");
  await trial.overrideState(agency, "ACTIVE"); await trial.overrideState(agency, "CANCELLED");
  row = (await db.select().from(dbs.businesses).where(eq(dbs.businesses.id, businessId)))[0]!;
  assert.equal(businessAutomationAllowed(row, now), false); assert.ok(row.trialStartedAt && row.trialEndsAt);
  const another = (await db.select().from(dbs.businesses).where(eq(dbs.businesses.id, otherBusinessId)))[0]!;
  assert.equal(another.trialStartedAt, null); assert.equal(another.state, "TRIAL");
  const unauthorized = createTrustedBusinessContext({ businessId, principal: { kind: "user", userId, sessionId: ulid() }, source: "test_harness", traceId: ulid(), capabilityGrants: ["business.read"] });
  await assert.rejects(trial.activate(unauthorized), /FORBIDDEN/);
  assert.equal((await db.select().from(dbs.notifications).where(and(eq(dbs.notifications.businessId, businessId), eq(dbs.notifications.type, "TRIAL_EXPIRED")))).length, 1);
  assert.ok((await db.select().from(dbs.auditLogs).where(eq(dbs.auditLogs.businessId, businessId))).length >= 6);
  console.log("Phase 7 trial: calendar-month activation, dated eligibility, expiry, notifications, sponsorship, pause, extension, authorization, and retained data passed");
} finally { await pool.end(); }
